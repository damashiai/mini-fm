-- Public read access for the catalog (the site has no user accounts; only the
-- single admin writes, and all writes go through service-role API routes that
-- verify Supabase Auth + ENABLE_WRITE_OPERATIONS).
drop policy if exists "public read" on public.artists;
create policy "public read" on public.artists for select using (true);
drop policy if exists "public read" on public.albums;
create policy "public read" on public.albums for select using (true);
drop policy if exists "public read" on public.album_artists;
create policy "public read" on public.album_artists for select using (true);
drop policy if exists "public read" on public.genres;
create policy "public read" on public.genres for select using (true);
drop policy if exists "public read" on public.languages;
create policy "public read" on public.languages for select using (true);
drop policy if exists "public read" on public.songs;
create policy "public read" on public.songs for select using (true);
drop policy if exists "public read" on public.song_artists;
create policy "public read" on public.song_artists for select using (true);
drop policy if exists "public read" on public.song_genres;
create policy "public read" on public.song_genres for select using (true);
drop policy if exists "public read" on public.playlists;
create policy "public read" on public.playlists for select using (true);

-- Anonymous clients record plays/likes keyed by their localStorage session id.
drop policy if exists "anon insert" on public.plays;
create policy "anon insert" on public.plays for insert with check (true);
drop policy if exists "public read" on public.plays;
create policy "public read" on public.plays for select using (true);
drop policy if exists "anon insert" on public.likes;
create policy "anon insert" on public.likes for insert with check (true);
drop policy if exists "anon delete own" on public.likes;
create policy "anon delete own" on public.likes for delete using (true);
drop policy if exists "public read" on public.likes;
create policy "public read" on public.likes for select using (true);

-- Storage buckets: `audio` (private, served via short-lived signed URLs so
-- <audio> streams straight from Supabase CDN with native Range support) and
-- `images` (public covers/artist photos).
